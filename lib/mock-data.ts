function trend(
  gpa: number,
  attendance: number,
  assessment: number,
): MonthlyMetric[] {
  const months = ["Feb", "Mar", "Apr", "May", "Jun", "Jul"];
  return months.map((month, index) => {
    const drift = (index - 2.5) * 0.04;
    return {
      month,
      gpa: Number(Math.min(4, Math.max(1.2, gpa + drift)).toFixed(2)),
      attendance: Math.min(100, Math.max(30, Math.round(attendance + drift * 8))),
      assessment: Math.min(100, Math.max(30, Math.round(assessment + drift * 6))),
    };
  });
}

function factors(
  items: Array<[string, ContributingFactor["level"]]>,
): ContributingFactor[] {
  return items.map(([name, level]) => ({ name, level }));
}

function course(
  courseId: string,
  courseCode: string,
  courseName: string,
  score: number,
  attendance: number,
): StudentCoursePerformance {
  const riskLevel =
    score < 50 || attendance < 60
      ? "high"
      : score < 65 || attendance < 75
        ? "medium"
        : "low";
  return { courseId, courseCode, courseName, score, attendance, riskLevel };
}

